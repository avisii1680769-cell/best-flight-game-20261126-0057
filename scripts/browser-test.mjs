// Test tooling only. No Playwright dependency is shipped in game/.
import { chromium } from '/opt/muse/assets/spaces/ts-runtime/dist/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { spawn } from 'node:child_process';
const server=spawn(process.execPath,['serve.ts'],{stdio:['ignore','pipe','inherit']});
await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);});
const browser=await chromium.launch({executablePath:'/home/hatch/.cache/ms-playwright/chromium-1208/chrome-linux64/chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1280,height:720},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
mkdirSync('artifacts',{recursive:true});
try {
  await page.goto('http://127.0.0.1:8080');
  await page.waitForFunction(()=>typeof window.render_game_to_text==='function');
  const state=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
  assert.equal((await state()).mode,'briefing');
  await page.keyboard.press('Enter');
  await page.evaluate(()=>window.advanceTime(1000));
  assert.equal((await state()).mode,'flying');
  assert.ok((await state()).z>50);
  await page.keyboard.press('p');
  assert.equal((await state()).mode,'paused');
  const z=(await state()).z;await page.evaluate(()=>window.advanceTime(1000));assert.equal((await state()).z,z);
  await page.keyboard.press('p');assert.equal((await state()).mode,'flying');
  await page.keyboard.down('ArrowRight');await page.evaluate(()=>window.advanceTime(800));await page.keyboard.up('ArrowRight');
  assert.ok((await state()).x>40);
  await page.keyboard.down('w');await page.evaluate(()=>window.advanceTime(500));await page.keyboard.up('w');
  assert.ok((await state()).throttle>.75);
  await page.keyboard.press('g');assert.equal((await state()).gear,true);
  await page.keyboard.press('g');assert.equal((await state()).gear,false);
  await page.keyboard.press('q');assert.equal((await state()).sound,false);
  await page.keyboard.press('v');assert.equal((await state()).reducedMotion,true);
  await page.setViewportSize({width:960,height:680});
  const bounds=await page.locator('canvas').boundingBox();assert.ok(bounds.width<=960&&bounds.height<=680);
  await page.mouse.click(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);assert.equal((await state()).mouse,true);
  await page.mouse.move(bounds.x+bounds.width*.8,bounds.y+bounds.height*.35);
  const oldAlt=(await state()).alt;await page.evaluate(()=>window.advanceTime(500));assert.ok((await state()).alt>oldAlt);
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));assert.equal((await state()).mode,'paused');
  await page.keyboard.press('p');await page.keyboard.press('m');
  await page.keyboard.press('r');assert.equal((await state()).passed,0);assert.equal((await state()).mode,'flying');
  await page.keyboard.down('ArrowDown');await page.evaluate(()=>window.advanceTime(5000));await page.keyboard.up('ArrowDown');
  assert.equal((await state()).mode,'crashed');assert.match((await state()).reason,/Terrain strike/);
  await page.screenshot({path:'artifacts/crash.png'});
  await page.keyboard.press('Enter');assert.equal((await state()).mode,'flying');
  await page.setViewportSize({width:1280,height:720});
  await page.context().setOffline(true);await page.evaluate(()=>window.advanceTime(1000));assert.ok((await state()).z>50);
  await page.screenshot({path:'artifacts/browser-smoke.png'});
  writeFileSync('artifacts/browser-smoke.json',JSON.stringify(await state(),null,2));
  assert.deepEqual(errors,[]);
  console.log('Browser PASS: launch, pause/resume/freeze, keyboard/mouse, throttle, gear, sound, reduced motion, resize, blur, terrain crash, restart, offline flight; 0 console errors');
} finally { await browser.close();server.kill(); }
